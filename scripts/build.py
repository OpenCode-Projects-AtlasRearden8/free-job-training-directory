#!/usr/bin/env python3
"""Build the Actually-Free Job Training Directory.

Reads data/entries.json (source of truth) and generates:
  - index.md           (top-level Markdown page)
  - pages/<id>.md      (one Markdown page per category)
  - site/index.html    (single-file static HTML, works offline via file://)

Edit the JSON, then re-run this script. Do not edit generated files.
Dependency-free: Python 3 standard library only.

Usage: python3 scripts/build.py   (run from the repository root)
"""

import json
import pathlib
import html

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "entries.json"
PAGES = ROOT / "pages"
SITE = ROOT / "site"

GEN_NOTE_MD = "<!-- GENERATED by scripts/build.py from data/entries.json -- edit the JSON, not this file -->"
GEN_NOTE_HTML = "<!-- GENERATED by scripts/build.py from data/entries.json -- edit the JSON, not this file -->"

HOUSE_RULES = [
    "Every offer listed here costs $0.00 to use in the way described. If an offer later grows a paywall, it gets flagged and fixed or removed.",
    "Nobody in this directory pays us. There are no affiliate links, no referral codes, and no tracking parameters on any URL.",
    "Each entry says exactly what \"free\" means for that offer: free everywhere, free with a library card, free course content but paid paper, or a government check that pays tuition for you.",
    "Certificates and CEUs matter or they don't exist here: if an entry mentions a paper trail, the entry tells you whether that paper is free.",
]


def load_data():
    data = json.loads(DATA.read_text(encoding="utf-8"))
    # Category membership lives on the section; mirror it onto entries for
    # validators and tooling so the JSON never carries the same fact twice.
    for cat in data.get("categories", []):
        for entry in cat.get("entries", []):
            entry["category"] = cat["id"]
    return data


def slug_anchor(entry_id):
    return "entry-" + entry_id


def md_escape_cell(text):
    return text.replace("|", "\\|").strip()


def date_note(data):
    return data.get("lastVerified", "verification date not recorded")


def build_index_md(data):
    lines = []
    lines.append(GEN_NOTE_MD)
    lines.append("")
    lines.append(f"# {data['siteTitle']}")
    lines.append("")
    lines.append(f"> {data['tagline']}")
    lines.append("")
    lines.append("A plain-English directory of upskilling that costs zero dollars: "
                 "university courses in audit mode, learning platforms unlocked by a "
                 "library card, certificates that are genuinely free (Google and cloud "
                 "basics included), US state and federal workforce programs, and CEU "
                 "samplers for licensed health workers.")
    lines.append("")
    total = sum(len(c["entries"]) for c in data["categories"])
    cats = len(data["categories"])
    lines.append(f"**{cats} categories, {total} offers.** Last verified: {date_note(data)}.")
    lines.append("")
    lines.append("## How to read every entry")
    lines.append("")
    for rule in HOUSE_RULES:
        lines.append(f"- {rule}")
    lines.append("")
    lines.append("## The directory")
    lines.append("")
    lines.append("| Category | Offers | Page |")
    lines.append("| --- | --- | --- |")
    for cat in data["categories"]:
        fname = f"pages/{cat['id']}.md"
        lines.append(f"| {cat['name']} | {len(cat['entries'])} | [{fname}]({fname}) |")
    lines.append("")
    lines.append("## Quick-start pointers")
    lines.append("")
    lines.append("- **\"I just want college-level courses, free.\"** Start with "
                 "[university audit mode](pages/audit-courses.md).")
    lines.append("- **\"I have a library card and never use it.\"** See what it already "
                 "pays for: [library platforms](pages/library-platforms.md).")
    lines.append("- **\"I want something to show a recruiter.\"** Go for the free "
                 "certificates: [Google, cloud basics & more](pages/free-certificates.md).")
    lines.append("- **\"Money is the only wall.\"** Let a public program pay for your "
                 "training: [state & federal workforce programs](pages/workforce-programs.md).")
    lines.append("- **\"I renew a license and need CE hours cheap.\"** Try "
                 "[health CEU samplers](pages/health-ceu.md).")
    lines.append("")
    lines.append("## Who this is for")
    lines.append("")
    lines.append("Anyone who needs new job skills and does not currently have tuition money: "
                 "career changers, returning workers, nurses renewing licenses on tight "
                 "budgets, small-business owners, and people who read a syllabus for fun. "
                 "The tone is plain English, step by step, never condescending.")
    lines.append("")
    lines.append("## Not the same site as our other directories")
    lines.append("")
    lines.append("- **free-learn-online-directory** covers the crowd-learner favorites for "
                 "learning anything online (textbook archives, language apps, coding walks).")
    lines.append("- **free-nursing-student-freebies-directory** covers freebies for "
                 "nursing *students* (flashcards, NCLEX practice, journals).")
    lines.append("- **This directory** covers career *upskilling* specifically: audit-mode "
                 "university courses, employer-readiness certificates, workforce funding, "
                 "and licensed-professional CEUs.")
    lines.append("")
    lines.append("## Honest notes")
    lines.append("")
    lines.append("- Links and offers were verified by hand on the date shown above. "
                  "Offers move; the `reports/` folder holds our latest link-check report.")
    lines.append("- Health CEU entries are for education and license renewal only. "
                  "They are never medical advice, and you should confirm credit types "
                  "with your licensing board before counting contact hours.")
    lines.append("- Government program terms (eligibility, amounts, windows) change. "
                  "The linked official pages are the source of truth.")
    lines.append("")
    lines.append("Built by [Asdale Dynamics, LLC](https://dylanasdale.github.io). "
                 "MIT licensed; no ads, no affiliates, no tracking.")
    lines.append("")
    text = "\n".join(lines)
    return text


def build_category_md(data, cat):
    lines = []
    lines.append(GEN_NOTE_MD)
    lines.append("")
    lines.append(f"# {cat['name']}")
    lines.append("")
    lines.append(f"_{len(cat['entries'])} offer(s). Part of The Actually-Free Job Training "
                 f"Directory; go [back to the index](../index.md)._")
    lines.append("")
    lines.append(cat["blurb"])
    lines.append("")
    lines.append("| Offer | Provider | What free means |")
    lines.append("| --- | --- | --- |")
    for e in cat["entries"]:
        short = e["freeWhat"].split(". ")[0].rstrip(".")
        lines.append(f"| [{e['title']}](#{slug_anchor(e['id'])}) | {e['provider']} | {md_escape_cell(short)} |")
    lines.append("")
    lines.append("---")
    lines.append("")
    for e in cat["entries"]:
        lines.append(f"<a id=\"{slug_anchor(e['id'])}\"></a>")
        lines.append("")
        lines.append(f"### {e['title']}")
        lines.append("")
        lines.append(f"**Provider:** {e['provider']}  ")
        lines.append(f"**Link:** <{e['url']}>")
        lines.append("")
        lines.append(f"**What it is:** {e['whatItIs']}")
        lines.append("")
        lines.append(f'**What "free" means:** {e["freeWhat"]}')
        lines.append("")
        lines.append(f"**Paper trail:** {e['paperTrail']}")
        lines.append("")
        lines.append(f"**Time needed:** {e['timeNeeded']}")
        lines.append("")
        lines.append(f"**Honest catch:** {e['catchOrLimit']}")
        lines.append("")
        lines.append(f"**Tags:** {', '.join(e['tags'])}")
        lines.append("")
        lines.append(f"**Verified free:** {e['verifiedOn']} · re-check due by {e['recheckBy']}")
        lines.append("")
        lines.append("---")
        lines.append("")
    lines.append("Health note (education only): listings here support learning and license "
                 "renewal, never medical decisions. Verify credit with your board.")
    lines.append("")
    return "\n".join(lines)


def esc(s):
    return html.escape(str(s), quote=True)


def build_site_html(data):
    title = data["siteTitle"]
    parts = []
    parts.append("<!DOCTYPE html>")
    parts.append('<html lang="en">')
    parts.append("<head>")
    parts.append('<meta charset="utf-8">')
    parts.append('<meta name="viewport" content="width=device-width, initial-scale=1">')
    parts.append(f"<title>{esc(title)}</title>")
    parts.append(f'<meta name="description" content="{esc(data["tagline"])}">')
    parts.append(GEN_NOTE_HTML)
    parts.append("<style>")
    parts.append(":root{--bg:#fdfdfb;--ink:#23252b;--muted:#5b6070;--accent:#1d5e79;--accent-soft:#e8f2f6;--line:#dfe2e8;--card:#ffffff;--warn:#8a5b00;--warn-soft:#fdf6e3;--ok:#1e6b45;--ok-soft:#e9f5ee;}"
                 "body{font-family:system-ui,-apple-system,'Segoe UI',Roboto,Helvetica,Arial,sans-serif;color:var(--ink);background:var(--bg);margin:0;line-height:1.6;}"
                 "main{max-width:56rem;margin:0 auto;padding:1.5rem 1.25rem 4rem;}"
                 "h1{font-size:1.9rem;line-height:1.25;margin:.5rem 0 .4rem;}"
                 "h2{font-size:1.35rem;margin-top:3rem;padding-bottom:.3rem;border-bottom:2px solid var(--line);}"
                 "h3{font-size:1.08rem;margin:.4rem 0;}"
                 "a{color:var(--accent);}"
                 ".tagline{color:var(--muted);font-size:1.05rem;margin:.2rem 0 1rem;}"
                 ".meta{color:var(--muted);font-size:.9rem;}"
                 ".toc{display:grid;grid-template-columns:repeat(auto-fit,minmax(15rem,1fr));gap:.75rem;margin:1.25rem 0;list-style:none;padding:0;}"
                 ".toc a{display:block;background:var(--card);border:1px solid var(--line);border-radius:.6rem;padding:.8rem 1rem;text-decoration:none;font-weight:600;}"
                 ".toc a span{display:block;font-weight:400;color:var(--muted);font-size:.85rem;}"
                 ".cat-blurb{background:var(--accent-soft);border-left:4px solid var(--accent);border-radius:.4rem;padding:.75rem 1rem;margin:.5rem 0 1rem;}"
                 "details{background:var(--card);border:1px solid var(--line);border-radius:.6rem;padding:0;margin:.75rem 0;}"
                 "summary{cursor:pointer;padding:.75rem 1rem;font-weight:600;list-style-position:inside;}"
                 "summary small{font-weight:400;color:var(--muted);}"
                 ".entry-body{padding:0 1rem 1rem;border-top:1px solid var(--line);padding-top:.75rem;}"
                 ".entry-body p{margin:.45rem 0;}"
                 ".label{font-weight:700;}"
                 ".rules{background:var(--card);border:1px solid var(--line);border-radius:.6rem;padding:.4rem 1rem .6rem;margin:1rem 0;}"
                 ".free{background:var(--ok-soft);border-left:4px solid var(--ok);border-radius:.4rem;padding:.55rem .8rem;}"
                 ".catch{background:var(--warn-soft);border-left:4px solid var(--warn);border-radius:.4rem;padding:.55rem .8rem;}"
                 "footer{border-top:1px solid var(--line);margin-top:3rem;padding-top:1rem;color:var(--muted);font-size:.9rem;}")
    parts.append("</style>")
    parts.append("</head>")
    parts.append("<body>")
    parts.append("<main>")
    parts.append(f"<h1>{esc(title)}</h1>")
    parts.append(f'<p class="tagline">{esc(data["tagline"])}</p>')
    total = sum(len(c["entries"]) for c in data["categories"])
    parts.append(f'<p class="meta">{len(data["categories"])} categories, {total} offers. '
                 f'Last verified: {esc(date_note(data))}. No ads, no affiliates, no tracking.</p>')

    parts.append('<h2 id="how-to-read">How to read every entry</h2>')
    parts.append('<div class="rules"><ul>')
    for rule in HOUSE_RULES:
        parts.append(f"<li>{esc(rule)}</li>")
    parts.append("</ul></div>")

    parts.append("<h2>The directory</h2>")
    parts.append('<ul class="toc">')
    for cat in data["categories"]:
        parts.append(f'<li><a href="#cat-{esc(cat["id"])}">{esc(cat["name"])}'
                     f'<span>{len(cat["entries"])} offers</span></a></li>')
    parts.append("</ul>")

    for cat in data["categories"]:
        parts.append(f'<h2 id="cat-{esc(cat["id"])}">{esc(cat["name"])}</h2>')
        parts.append(f'<div class="cat-blurb">{esc(cat["blurb"])}</div>')
        for e in cat["entries"]:
            parts.append(f'<details id="{esc(slug_anchor(e["id"]))}">')
            parts.append(
                f"<summary>{esc(e['title'])} <small>— {esc(e['provider'])}"
                f" · verified free {esc(e['verifiedOn'])}</small></summary>"
            )
            parts.append('<div class="entry-body">')
            parts.append(f'<p><span class="label">Link:</span> <a href="{esc(e["url"])}" '
                         f'rel="noopener">{esc(e["url"])}</a></p>')
            parts.append(f'<p><span class="label">What it is:</span> {esc(e["whatItIs"])}</p>')
            parts.append(f'<p class="free"><span class="label">What “free” means:</span> {esc(e["freeWhat"])}</p>')
            parts.append(f'<p><span class="label">Paper trail:</span> {esc(e["paperTrail"])}</p>')
            parts.append(f'<p><span class="label">Time needed:</span> {esc(e["timeNeeded"])}</p>')
            parts.append(f'<p class="catch"><span class="label">Honest catch:</span> {esc(e["catchOrLimit"])}</p>')
            parts.append(f'<p class="meta">Verified free on {esc(e["verifiedOn"])} · '
                         f're-check due by {esc(e["recheckBy"])} · tags: '
                         f'{esc(", ".join(e["tags"]))}</p>')
            parts.append("</div>")
            parts.append("</details>")

    parts.append('<h2 id="notes">Honest notes</h2>')
    parts.append("<ul>")
    parts.append(f"<li>Links and offers were verified by hand on {esc(date_note(data))}. "
                 "Offers move; see <code>reports/</code> for the latest link-check report.</li>")
    parts.append("<li>Health CEU entries are for education and license renewal only — never "
                 "medical advice. Confirm credit types with your licensing board before "
                 "counting contact hours.</li>")
    parts.append("<li>Government programs change terms (eligibility, amounts, windows). The "
                 "linked official pages are the source of truth.</li>")
    parts.append("</ul>")
    parts.append("<footer>Built by Asdale Dynamics, LLC · "
                 '<a href="https://dylanasdale.github.io" rel="noopener">dylanasdale.github.io</a> · '
                 "MIT licensed · companion to the free-learn-online-directory and "
                 "free-nursing-student-freebies-directory.</footer>")
    parts.append("</main>")
    parts.append("</body>")
    parts.append("</html>")
    return "\n".join(parts)


def main():
    data = load_data()
    PAGES.mkdir(exist_ok=True)
    SITE.mkdir(exist_ok=True)

    for old in PAGES.glob("*.md"):
        old.unlink()
    for old in SITE.glob("*.html"):
        old.unlink()

    (ROOT / "index.md").write_text(build_index_md(data), encoding="utf-8")
    for cat in data["categories"]:
        (PAGES / f"{cat['id']}.md").write_text(build_category_md(data, cat), encoding="utf-8")
    (SITE / "index.html").write_text(build_site_html(data), encoding="utf-8")

    total = sum(len(c["entries"]) for c in data["categories"])
    print(f"Built index.md, {len(data['categories'])} category pages, "
          f"site/index.html ({total} entries).")


if __name__ == "__main__":
    main()
